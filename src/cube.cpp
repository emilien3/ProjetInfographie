Cube::Cube()
{
    // (3 Pos + 3 Norm + 2 UV = 8 floats par sommet)
    int nbFloats = sizeof(vertices) / sizeof(float);
    for (int i = 0; i < nbFloats; i += 8) {
        Vertex vertex;
        
        // position
        vertex.Position = glm::vec3(vertices[i], vertices[i+1], vertices[i+2]);
        
        // normale
        vertex.Normal = glm::vec3(vertices[i+3], vertices[i+4], vertices[i+5]);
        
        // UV
        vertex.TexCoords = glm::vec2(vertices[i+6], vertices[i+7]);

        m_vertices.push_back(vertex);
    }
    
    setupMesh();
}